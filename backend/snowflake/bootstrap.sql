-- Run once in Snowsight using an account administrator role.
-- Then run setup.sql to create and seed the application tables.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RELAY_APP;

CREATE WAREHOUSE IF NOT EXISTS RELAY_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RELAY;
CREATE SCHEMA IF NOT EXISTS RELAY.APP;

GRANT USAGE ON WAREHOUSE RELAY_WH TO ROLE RELAY_APP;
GRANT USAGE ON DATABASE RELAY TO ROLE RELAY_APP;
GRANT USAGE, CREATE TABLE ON SCHEMA RELAY.APP TO ROLE RELAY_APP;
GRANT ROLE RELAY_APP TO USER RAMLOLS2604;